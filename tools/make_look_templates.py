"""Build scene_look_templates.py from the look-probe captures.

Probe: client/look_probe.js in an --apartment-probe build (never published).
Inputs (private, analysis/look/): <scene>-wire.bin, the body Python sent, and
<scene>-look.bin, the client's own re-encode after the probe gave the local
player the marker look (both in the player metadata and on its character).
"""
import sqlite3
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import scene
from stream import Writer

d = ROOT / 'analysis/look'
ns = int(sqlite3.connect(ROOT / '.local/accounts.sqlite3').execute(
    "select value from settings where name='namespace'").fetchone()[0])
ident = Writer().compact((ns << 32) | 4, 64).bytes()
NAME = (2).to_bytes(4, 'big') + b'hi'


def parts(name):
    look = (d / f'{name}-look.bin').read_bytes()
    first = look.index(ident)
    second = look.index(ident, first + 1)
    return look, look[first + len(ident):second], look[second + len(ident):]


def homes(name):
    look, middle, suffix = parts(name)
    assert suffix.count(NAME) == 1 and suffix.endswith(b'\0')
    return middle, suffix.replace(NAME, scene._NAME_FIELD)


out = ['"""Generated by tools/make_look_templates.py from client re-encodes; see scene.apply_look."""', '']
def emit(name, data):
    out.append(f'{name} = bytes.fromhex(')
    out.extend(f'    "{line}"' for line in textwrap.wrap(data.hex(), 64))
    out.append(')')
    out.append('')

look, middle, suffix = parts('apt')
assert look[:50] == scene._PREFIX
emit('APARTMENT_MIDDLE', middle); emit('APARTMENT_SUFFIX', homes('apt')[1])
look, middle, suffix = parts('cz')
emit('COOL_ZONE_MIDDLE', middle); emit('COOL_ZONE_SUFFIX', homes('cz')[1])
look, middle, suffix = parts('dt')
assert look[:50] == scene._PROGRESSION_PREFIX
emit('PROGRESSION_MIDDLE', middle); emit('PROGRESSION_SUFFIX', suffix)
# Shrine Canyon: the capture carries that battle's jobs and XP table. Keep the
# client's frame and metadata, then the template's own battle-start tail;
# canyon_scene appends the extra trailing zero after filling the tail.
look, middle, suffix = parts('canyon')
wire = (d / 'canyon-wire.bin').read_bytes()
tail = 0
while wire[-1 - tail] == look[-2 - tail]:
    tail += 1
assert look[-1] == 0 and tail >= 260
start = len(wire) - tail
template = scene.canyon_scene((ns << 32) | 4)
assert wire[:start] == template[:start]
keep = len(suffix) - 1 - tail
emit('CANYON_MIDDLE', middle); emit('CANYON_SUFFIX', suffix[:keep] + template[start:])
(ROOT / 'scene_look_templates.py').write_text('\n'.join(out), encoding='utf-8')
print('written')
